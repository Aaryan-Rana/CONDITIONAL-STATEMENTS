//WRITE A PROGRAM TO CHECK IF THE NO. IS EVEN OR ODD

public class Ifelse {
    public static void main(String[] args) {
        int number = 5;
        if (number % 2 == 0) {
            System.out.println("The number is even");
            
        }
        else{
            System.out.println("The number is odd");
        }
    }
}